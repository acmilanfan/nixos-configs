local core = require("plugins.org.core")

local M = {}

-- Keys the preview handles itself; their source mappings must not shadow
-- them. `nvim_buf_get_keymap` returns literal spaces when `mapleader` is
-- Space, so compare termcode-expanded forms rather than symbolic spellings.
local NATIVE_KEYS = { "q", "<Leader>ov", "<Leader>oj", "<CR>", "<Space>", "gx", "<C-o>", "<C-i>" }

local function native_keys()
  local keys = {}
  for _, key in ipairs(NATIVE_KEYS) do
    keys[vim.keycode(key)] = true
  end
  return keys
end

-- Run a preview action in the source buffer, keeping the preview as the
-- visible buffer. Org's own mappings stay authoritative for editing.
local function in_source(state, fn)
  local view = vim.api.nvim_win_call(state.win, function() return vim.fn.winsaveview() end)
  local ok, err = pcall(function()
    vim.api.nvim_win_set_buf(state.win, state.src)
    vim.api.nvim_win_call(state.win, fn)
  end)
  vim.api.nvim_win_set_buf(state.win, state.preview)
  vim.api.nvim_win_call(state.win, function() pcall(vim.fn.winrestview, view) end)
  require("plugins.org.preview").refresh(state)
  if not ok then error(err, 0) end
end

function M.toggle_checkbox(state, line)
  if not state or not line or not line.checkbox then return end
  if not vim.api.nvim_buf_is_valid(state.src) then return end
  if not vim.api.nvim_buf_is_valid(state.preview) then return end
  if not (state.win and vim.api.nvim_win_is_valid(state.win)) then return end

  in_source(state, function()
    vim.api.nvim_win_set_cursor(0, { line.source, line.checkbox.col })
    require("orgmode").action("org_mappings.toggle_checkbox")
  end)
end

-- Read a link target without giving it a window. A loaded buffer is preferred
-- so unsaved edits are respected.
local function target_lines(path)
  local buf = vim.fn.bufnr(path)
  if buf ~= -1 and vim.api.nvim_buf_is_loaded(buf) then
    return vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  end
  if vim.fn.filereadable(path) == 0 then return nil end
  local ok, lines = pcall(vim.fn.readfile, path)
  if not ok then return nil end
  return lines
end

-- Org headline links match a title without its TODO keyword or tags.
local function todo_keywords()
  local ok, keywords = pcall(function()
    return require("orgmode.config"):get_todo_keywords():keys()
  end)
  if ok then return keywords end
  return {}
end

local function title_forms(text, keywords)
  local keyword, rest = text:match("^(%u+)%s+(.+)$")
  local plain = (keyword and keywords[keyword]) and rest or text
  local forms = { text:lower(), plain:lower() }
  forms[#forms + 1] = forms[1]:gsub("%s+:[^%s]+:$", "")
  forms[#forms + 1] = forms[2]:gsub("%s+:[^%s]+:$", "")
  return forms
end

-- Jump to the headline owning a CUSTOM_ID property, as generated by
-- `core.heading_selector`. A file-level property has no owning heading.
local function custom_id_line(lines, id)
  for i, text in ipairs(lines) do
    local key, value = text:match("^%s*:([%w_%-]+):%s*(.-)%s*$")
    if key and key:upper() == "CUSTOM_ID" and value == id then
      for j = i - 1, 1, -1 do
        if lines[j]:match("^%*+%s") then return j end
      end
      return nil
    end
  end
  return nil
end

-- Resolve an Org file selector (::12, ::*Heading, or ::#CUSTOM_ID) to a line
-- number. A plain file link has no selector; unknown selectors and missing
-- targets fall back to the first line.
local function selector_line(lines, suffix)
  local selector = suffix and suffix:match("^::(.*)$") or ""
  selector = selector:gsub("%s+%+%d+$", "")
  if selector == "" then return nil end
  local number = selector:match("^(%d+)$")
  if number then return math.max(1, math.min(tonumber(number), math.max(#lines, 1))) end
  local id = selector:match("^#(.+)$")
  if id then return custom_id_line(lines, id) or 1 end
  local title = vim.trim(selector:match("^%*(.*)$") or "")
  if title == "" then return 1 end
  local keywords = todo_keywords()
  local wanted = title_forms(title, keywords)
  for i, text in ipairs(lines) do
    local heading = text:match("^%*+%s+(.*)$")
    if heading then
      local forms = title_forms(heading, keywords)
      for _, want in ipairs(wanted) do
        if want ~= "" then
          for _, form in ipairs(forms) do
            if form:find(want, 1, true) == 1 then return i end
          end
        end
      end
    end
  end
  return 1
end

local function open_file(state, target)
  local path, suffix = core.local_target(vim.api.nvim_buf_get_name(state.src), target)
  if not path then return nil end
  local lines = target_lines(path)
  if not lines then
    vim.notify("Cannot open Org link target: " .. path, vim.log.levels.WARN)
    return false
  end
  vim.cmd("edit " .. vim.fn.fnameescape(path))
  local line = selector_line(lines, suffix)
  if line then
    pcall(vim.api.nvim_win_set_cursor, 0, { math.min(line, math.max(vim.fn.line("$"), 1)), 0 })
  end
  return true
end

-- A reflowed preview line can contain words from several source lines while a
-- link only records the column within its own line. Find the literal link in
-- the source paragraph that starts at the rendered line's first source line;
-- fall back to the first-line approximation when it is not found.
local function link_position(state, link)
  local lines = vim.api.nvim_buf_get_lines(state.src, 0, -1, false)
  local first = math.max(math.min(link.source or 1, math.max(#lines, 1)), 1)
  local needle = "[[" .. link.target .. "]"
  local i = first
  while i <= #lines and not lines[i]:match("^%s*$") do
    local start = lines[i]:find(needle, 1, true)
    if start then return i, start - 1 end
    i = i + 1
  end
  return first, math.max(link.source_col or 0, 0)
end

-- The link whose rendered text covers a preview cursor column. Carrying the
-- rendered line's first source line keeps reflowed id links resolvable.
function M.link_at(line, col)
  if not (line and line.links) then return nil end
  for _, link in ipairs(line.links) do
    if col >= link.start_col and col < link.end_col then
      return { target = link.target, source_col = link.source_col, source = line.source }
    end
  end
  return nil
end

local function first_nonblank(state, source)
  local text = vim.api.nvim_buf_get_lines(state.src, source - 1, source, false)[1] or ""
  local col = text:find("%S")
  return (col or 1) - 1
end

-- Source position behind a rendered line and preview column. Checkboxes and
-- links keep their exact source column; every other line uses its source
-- row's first non-blank column.
local function source_position(state, line, col)
  -- A link under the cursor wins even on a checkbox line.
  local link = M.link_at(line, col)
  if link then return link_position(state, link) end
  if line.checkbox then
    return line.source, line.checkbox.col
  end
  return line.source, first_nonblank(state, line.source)
end

-- Leave the preview for the source position behind the current rendered line.
-- Checkboxes and links keep their exact source column; every other line,
-- including table borders, uses its source row's first non-blank column.
-- Synthetic lines (block separators and the filename fallback title) have no
-- source row, so they leave the preview open.
function M.jump(state)
  if not state or not state.lines then return false end
  if not vim.api.nvim_buf_is_valid(state.src) then return false end
  if not vim.api.nvim_buf_is_valid(state.preview) then return false end
  if not (state.win and vim.api.nvim_win_is_valid(state.win)) then return false end
  if vim.api.nvim_win_get_buf(state.win) ~= state.preview then return false end

  local cursor = vim.api.nvim_win_get_cursor(state.win)
  local line = state.lines[cursor[1]]
  if not line or not line.source or line.source < 1 then return false end

  local source, col = source_position(state, line, cursor[2])
  require("plugins.org.preview").close(state.src, { jump_to = { source, col } })
  return true
end

-- Return to the preview when a prompt that stole focus closes.
local function focus_preview(state)
  if not vim.api.nvim_buf_is_valid(state.preview) then return end
  if not (state.win and vim.api.nvim_win_is_valid(state.win)) then return end
  if vim.api.nvim_win_get_buf(state.win) ~= state.preview then return end
  vim.api.nvim_set_current_win(state.win)
end

-- Replay a source-buffer Org mapping at the position behind the preview
-- cursor. The preview buffer is restored immediately so an asynchronous
-- prompt edits the source, not the rendered copy.
function M.run(state, lhs)
  if not (state and state.lines and lhs) then return false end
  if not vim.api.nvim_buf_is_valid(state.src) then return false end
  if not vim.api.nvim_buf_is_valid(state.preview) then return false end
  if not (state.win and vim.api.nvim_win_is_valid(state.win)) then return false end
  if vim.api.nvim_win_get_buf(state.win) ~= state.preview then return false end

  local cursor = vim.api.nvim_win_get_cursor(state.win)
  local line = state.lines[cursor[1]]
  if not line or not line.source or line.source < 1 then return false end

  local source, col = source_position(state, line, cursor[2])
  local view = vim.api.nvim_win_call(state.win, function() return vim.fn.winsaveview() end)
  local tick = vim.api.nvim_buf_get_changedtick(state.src)

  vim.api.nvim_win_set_buf(state.win, state.src)
  pcall(vim.api.nvim_win_set_cursor, state.win, { source, col })
  vim.api.nvim_set_current_win(state.win)
  local ok, err = pcall(vim.api.nvim_feedkeys, vim.keycode(lhs), "mx", false)

  -- Restore the preview even while an asynchronous prompt is still open. The
  -- prompt keeps focus; the one-shot autocmd returns focus to the preview.
  if vim.api.nvim_buf_is_valid(state.preview) and vim.api.nvim_win_is_valid(state.win) then
    vim.api.nvim_win_set_buf(state.win, state.preview)
    vim.api.nvim_win_call(state.win, function() pcall(vim.fn.winrestview, view) end)
  end

  local current = vim.api.nvim_get_current_win()
  if current ~= state.win and vim.api.nvim_win_is_valid(current)
    and vim.api.nvim_win_get_config(current).relative ~= "" then
    vim.api.nvim_create_autocmd("WinClosed", {
      once = true,
      pattern = tostring(current),
      desc = "Focus the Org preview after its prompt closes",
      callback = function() focus_preview(state) end,
    })
  end

  -- Re-render only when the mapping changed the source; the persistent source
  -- watcher covers asynchronous edits. An action that merely moves the source
  -- cursor leaves the preview as it is.
  if vim.api.nvim_buf_get_changedtick(state.src) ~= tick then
    vim.schedule(function() require("plugins.org.preview").refresh(state) end)
  end
  if not ok then error(err, 0) end
  return true
end

-- Mirror the source buffer's normal-mode mappings onto the preview. Replaying
-- the original key in the source keeps the Org mapping authoritative.
function M.mirror(state)
  if not state then return false end
  if not vim.api.nvim_buf_is_valid(state.src) then return false end
  if not vim.api.nvim_buf_is_valid(state.preview) then return false end

  local native = native_keys()
  for _, map in ipairs(vim.api.nvim_buf_get_keymap(state.src, "n")) do
    local lhs = map.lhs
    if lhs and lhs ~= "" and not native[vim.keycode(lhs)] then
      vim.keymap.set("n", lhs, function() M.run(state, lhs) end, {
        buffer = state.preview,
        nowait = true,
        silent = true,
        desc = "Org preview: " .. (map.desc or lhs),
      })
    end
  end
  return true
end

-- Leave the target Org mapping in charge of id: and other custom links. The
-- preview stays loaded (bufhidden=hide) even though the action replaces it.
-- When the action opens nothing, the preview returns instead of stranding the
-- user in the raw source buffer.
local function open_at_source(state, link)
  local win = vim.api.nvim_get_current_win()
  local view = vim.api.nvim_win_call(win, function() return vim.fn.winsaveview() end)
  local line, col = link_position(state, link)
  vim.api.nvim_win_set_buf(win, state.src)
  local before
  local ok, err = pcall(function()
    vim.api.nvim_win_call(win, function()
      pcall(vim.api.nvim_win_set_cursor, 0, { line, col })
      before = vim.api.nvim_win_get_cursor(0)
      require("orgmode").action("org_mappings.open_at_point")
    end)
  end)
  local target = vim.api.nvim_win_get_buf(win)
  local cursor = vim.api.nvim_win_get_cursor(win)
  if not vim.api.nvim_buf_is_valid(state.preview) then
    if not ok then error(err, 0) end
    return true
  end
  vim.api.nvim_win_set_buf(win, state.preview)
  vim.api.nvim_win_call(win, function() pcall(vim.fn.winrestview, view) end)
  if not ok then error(err, 0) end
  if target == state.src and vim.deep_equal(before, cursor) then
    -- The action opened nothing; the preview is already back.
    return true
  end
  -- The action made the source line the previous jumplist entry. Replay the
  -- edit from the preview so Ctrl-o returns to the link, not the source line.
  local name = vim.api.nvim_buf_get_name(target)
  if vim.bo[target].buftype == "" and name ~= "" and vim.fn.filereadable(name) == 1
    and pcall(vim.cmd, "edit " .. vim.fn.fnameescape(name)) then
    pcall(vim.api.nvim_win_set_cursor, win, cursor)
    return true
  end
  vim.api.nvim_win_set_buf(win, target)
  pcall(vim.api.nvim_win_set_cursor, win, cursor)
  return true
end

function M.open_link(state, link)
  if not (state and link and link.target) then return false end
  if not vim.api.nvim_buf_is_valid(state.src) then return false end

  local scheme = link.target:match("^(%a[%w+.-]*):")
  scheme = scheme and scheme:lower()
  if scheme == "https" or scheme == "http" or scheme == "mailto" then
    vim.ui.open(link.target)
    return true
  end

  local opened = open_file(state, link.target)
  if opened ~= nil then return opened end
  return open_at_source(state, link)
end

return M
